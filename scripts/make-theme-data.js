#!/usr/bin/env node
// Builds the theme's data files from products.js and swatches.js. Run again after changing either:
//   assets/vl-data.js               colours, lengths, packs and "complete your kit" pairings (no costs)
//   snippets/product-static.liquid  per-product text: menu name, eyebrow, summary, blurb, specs, guides, pairings
//   snippets/vl-order.liquid        the order products are listed in
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.join(__dirname, "..");
const read = f => fs.readFileSync(path.join(ROOT, f), "utf8");
const { CATEGORIES, CATALOGUE } = vm.runInNewContext(read("products.js") + "\n;({CATEGORIES,CATALOGUE})");
const SWATCH = vm.runInNewContext(read("swatches.js") + "\n;SWATCH");
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const slugOf = id => CATALOGUE[id].slug;

// ---------- assets/vl-data.js ----------
const products = {};
for (const [id, P] of Object.entries(CATALOGUE)) {
  const match = {};
  for (const [acc, map] of Object.entries(P.match || {})) match[slugOf(acc)] = map;
  products[P.slug] = {
    id, name: P.name, menu: P.menu || P.name, cat: P.category, hair: P.category === "extensions",
    lens: P.lens, wts: P.wts.map(w => w[0]),
    colours: P.colours.map(c => [c[0], c[1], c[3] || null, c[4] || SWATCH[c[3]] || ["#bbb", "#ccc", "#ddd"]]),
    pairs: (P.pairsWith || []).map(([acc, why]) => [slugOf(acc), why]),
    match,
  };
}
const cats = CATEGORIES.map(c => ({ id: c.id, slug: c.slug, name: c.name,
  items: Object.values(CATALOGUE).filter(p => p.category === c.id).map(p => p.slug) }));
fs.writeFileSync(path.join(ROOT, "assets/vl-data.js"),
  "// Generated by scripts/make-theme-data.js. Do not edit by hand.\nwindow.VL=" + JSON.stringify({ cats, products }) + ";\n");

// ---------- snippets/product-static.liquid ----------
const summary = p => `${p.colours.length} ${p.colourWord || "shades"}${p.lens[0] ? ` · ${p.lens[0]}–${p.lens[p.lens.length - 1]}"` : ""}`;
const all = Object.entries(CATALOGUE);
const part = (name, each, fallback) =>
  `{%- when '${name}' -%}\n  {%- case product.handle -%}\n` +
  all.map(([id, P]) => { const v = each(id, P); return v == null ? "" : `    {%- when "${P.slug}" -%}${v}\n`; }).join("") +
  `    {%- else -%}${fallback}\n  {%- endcase -%}\n`;
const usedBy = id => all.filter(([, H]) => (H.pairsWith || []).some(([a]) => a === id)).map(([, H]) => H.slug);
let out = "{%- comment -%} Generated by scripts/make-theme-data.js from products.js. Do not edit by hand. {%- endcomment -%}\n{%- case part -%}\n";
out += part("menu", (id, P) => esc(P.menu || P.name), "{{ product.title | escape }}");
out += part("eyebrow", (id, P) => esc(P.eyebrow), "{{ product.type | escape }}");
out += part("summary", (id, P) => esc(summary(P)), "{% if product.variants.size > 1 %}{{ product.variants.size }} options{% endif %}");
out += part("blurb", (id, P) => esc(P.blurb), "");
out += part("specs", (id, P) => P.specs.map(r => `<tr><td>${esc(r[0])}</td><td>${esc(r[1])}</td></tr>`).join(""), "");
// Width and height of a JPEG in assets/, so the browser can reserve the space before the photo loads.
function jpegSize(file) {
  const d = fs.readFileSync(path.join(ROOT, "assets", file));
  for (let i = 2; i < d.length;) {
    if (d[i] !== 0xff) { i++; continue; }
    const m = d[i + 1];
    if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return [d.readUInt16BE(i + 7), d.readUInt16BE(i + 5)];
    i += 2 + d.readUInt16BE(i + 2);
  }
  throw new Error("could not read the size of assets/" + file);
}
out += part("guides", (id, P) => !(P.guides || []).length ? null : P.guides.map(g => { const [w, h] = jpegSize(g[0] + ".jpg"); return (
  `<figure><img src="{{ '${g[0]}.jpg' | asset_url }}" alt="${esc(g[1])}" loading="lazy" width="${w}" height="${h}"><figcaption class="eyebrow">${esc(g[1])}</figcaption></figure>`); }).join(""), "");
out += part("pairs", (id, P) => !(P.pairsWith || []).length ? null : P.pairsWith.map(([acc, why]) => slugOf(acc) + "||" + esc(why)).join(";;"), "");
out += part("usedby", id => usedBy(id).length ? usedBy(id).join(",") : null, "");
out += "{%- endcase -%}\n";
fs.mkdirSync(path.join(ROOT, "snippets"), { recursive: true });
fs.writeFileSync(path.join(ROOT, "snippets/product-static.liquid"), out);

// ---------- snippets/vl-order.liquid ----------
fs.writeFileSync(path.join(ROOT, "snippets/vl-order.liquid"),
  "{%- comment -%} Generated by scripts/make-theme-data.js. {%- endcomment -%}" + all.map(([, P]) => P.slug).join(","));

// Guide photos live in assets/ (copied from images/ on the main branch).
const guideImgs = [...new Set(all.flatMap(([, P]) => (P.guides || []).map(g => g[0])))];
const missing = guideImgs.filter(g => !fs.existsSync(path.join(ROOT, "assets", g + ".jpg")));
if (missing.length) { console.error("Missing guide photos in assets/: " + missing.join(", ")); process.exit(1); }
console.log(`theme data written: ${all.length} products, ${cats.length} categories`);
